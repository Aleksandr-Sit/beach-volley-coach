"""Каноничные названия упражнений + нормализация свободных записей результата.

Цель: запись пользователя («жим гантелей нейтральный хват сидя 2*12,5») привести
к единому виду и сопоставить с упражнением программы →
«Жим гантелей нейтральным хватом сидя — 2×12.5».
"""
from __future__ import annotations

import re

# (каноничное имя, [подстроки-ключи]). Порядок: специфичные ПЕРЕД общими.
CANON: list[tuple[str, list[str]]] = [
    ("Болгарский сплит-присед", ["болгар", "сплит-присед", "сплит"]),
    ("Выпады с гантелями", ["выпад"]),
    ("Присед со штангой", ["присед", "squat", "присяд"]),
    ("Тяга трап-гриф", ["трап-гриф", "трап", "трэп", "trap"]),
    ("Румынская тяга", ["румын", "rdl"]),
    ("Ягодичный мост", ["ягодич", "мост"]),
    ("Ландмайн-жим", ["ландмайн", "landmine"]),
    ("Жим гантелей нейтральным хватом сидя", ["жим гантел", "жим ганте", "гантел жим"]),
    ("Тяга гантели в наклоне", ["тяга гантел", "гантел в наклон"]),
    ("Тяга штанги в наклоне", ["тяга штанг", "штанг в наклон"]),
    ("Тяга верхнего блока", ["верхн блок", "тяга блок", "верхнего блок"]),
    ("Подтягивания", ["подтяг"]),
    ("Отжимания на кольцах", ["отжим"]),
    ("Наружная ротация плеча", ["ротаци"]),
    ("Face pull", ["face", "фейс", "фэйс"]),
    ("Y-T-W лопаточные", ["y-t-w", "ytw", "лопаточ"]),
    ("Планка", ["планк"]),
    ("Паллоф-пресс", ["паллоф"]),
    ("Выпрыгивания с места", ["выпрыг"]),
    ("Дроп-приземления", ["дроп", "приземлен"]),
    ("Подъёмы на носки", ["на носк", "носки", "икры"]),
    ("Баланс на одной ноге", ["баланс"]),
    ("Игровая тренировка", ["игров"]),
    ("Групповая тренировка", ["группов"]),
    ("Техническая тренировка", ["техник"]),
    ("Игра", ["игра", "матч"]),
]


def match_exercise(name_part: str) -> str | None:
    t = name_part.lower()
    for canon, keys in CANON:
        if any(k in t for k in keys):
            return canon
    return None


def _norm_nums(s: str) -> str:
    s = re.sub(r"(\d)\s*[*xх×]\s*(\d)", r"\1×\2", s)   # 2*12 / 2x12 / 2х12 -> 2×12
    s = re.sub(r"(\d)\s+на\s+(\d)", r"\1×\2", s)          # 22 на 10 -> 22×10
    return re.sub(r"\s+", " ", s).strip()


def normalize_log(text: str) -> str:
    """Приводит свободную запись к единому формату, сопоставляя названия."""
    text = re.sub(r"(\d),(\d)", r"\1.\2", text)  # десятичная запятая 12,5 -> 12.5
    segments = re.split(r"[;,]| и ", text)
    out: list[str] = []
    for seg in segments:
        seg = seg.strip()
        if not seg:
            continue
        m = re.search(r"\d", seg)
        if m:
            name_part, nums = seg[: m.start()].strip(), _norm_nums(seg[m.start():])
        else:
            name_part, nums = seg, ""
        canon = match_exercise(name_part)
        if canon:
            out.append(f"{canon} — {nums}" if nums else canon)
        else:
            out.append(_norm_nums(seg))
    return "; ".join(out)
