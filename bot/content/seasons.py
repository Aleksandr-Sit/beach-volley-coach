DEFAULT_SEASON = "beach"


def season(key: str | None) -> dict:
    return SEASONS.get(key or DEFAULT_SEASON, SEASONS[DEFAULT_SEASON])


def label(key: str | None) -> str:
    return season(key)["label"]


def slots_for(key: str) -> list[tuple]:
    return list(SEASONS[key]["slots"])


def suggest_for_month(month: int) -> str:
    """Какой сезон логичен для месяца в Самаре. Подсказка, решает атлет.

    Сентябрь отнесён к межсезонью намеренно: песок к середине месяца уже
    заканчивается, и подсказывать «пляж» в момент, когда сезон закрывается,
    бессмысленно. Апрель — тоже межсезонье: подготовка к выходу на песок.
    """
    if month in (5, 6, 7, 8):
        return "beach"
    if month in (4, 9, 10, 11):
        return "offseason"
    return "indoor"
