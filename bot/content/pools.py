def pick(pool: list, variant: int):
    """Вариант из пула по кругу. Отрицательные и большие значения безопасны."""
    return pool[variant % len(pool)] if pool else None


def reps(entry: tuple, heavy: bool) -> str:
    """Повторы под нагрузку дня: entry = (название, тяжёлая, средняя)."""
    return entry[1] if heavy else entry[2]


def line(entry: tuple, heavy: bool) -> str:
    return f"{entry[0]} — {reps(entry, heavy)}"
